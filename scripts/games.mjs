#!/usr/bin/env node
// Game import pipeline: pulls a "Can You ..." game from its own project into the hub.
//
//   npm run games:import                   re-import every game in games.sources.json
//   npm run games:import -- survive        re-import one game by id
//   npm run games:import -- ../canyounew   import a new project (and add it to games.sources.json)
//   npm run games:check -- ../canyounew    validate a project against the contract, change nothing
//   npm run games:list                     show imported games and where they came from
//
// Flags: --skip-checks skips the game's own typecheck and tests.
//
// The contract a game must meet is in docs/GAME_CONTRACT.md.

import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HUB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES_FILE = path.join(HUB, 'games.sources.json');
const IMPORTED = path.join(HUB, 'imported');
const API = path.join(HUB, 'api');
const GENERATED_REGISTRY = path.join(HUB, 'apps/web/src/games.generated.ts');
const HUB_TIMEZONE = 'America/Chicago';
const RESERVED_IDS = new Set(['hub', 'api', 'about', 'archive', 'assets', 'imported', 'shared']);
const KINDS = ['luck', 'skill', 'crowd', 'knowledge'];
const GENERATED_HEADER = '// Generated by `npm run games:import`. Do not edit.';

class ContractError extends Error {}

// ---------- small helpers ----------------------------------------------------

const rel = (p) => path.relative(HUB, p) || '.';
const log = (msg) => console.log(msg);
const step = (msg) => console.log(`  • ${msg}`);

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function writeFile(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function grepDir(dir, needle) {
  return walk(dir).some((f) => /\.(ts|tsx|js|mjs)$/.test(f) && fs.readFileSync(f, 'utf8').includes(needle));
}

function git(cwd, args) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return null;
  }
}

function run(cwd, cmd, args, env = {}) {
  const r = spawnSync(cmd, args, { cwd, stdio: 'inherit', env: { ...process.env, ...env } });
  if (r.status !== 0) throw new Error(`\`${cmd} ${args.join(' ')}\` failed in ${cwd}`);
}

// ---------- sources -----------------------------------------------------------

function readSources() {
  return fs.existsSync(SOURCES_FILE) ? readJson(SOURCES_FILE) : { games: [] };
}

function saveSource(id, source) {
  const sources = readSources();
  const relSource = path.relative(HUB, source);
  const existing = sources.games.find((g) => g.id === id);
  if (existing) existing.source = relSource;
  else sources.games.push({ id, source: relSource });
  writeFile(SOURCES_FILE, JSON.stringify(sources, null, 2) + '\n');
}

/** Turn CLI targets (ids or paths) into absolute project directories. */
function resolveTargets(targets) {
  const sources = readSources();
  if (targets.length === 0) {
    if (sources.games.length === 0) throw new Error('No games in games.sources.json. Pass a project path.');
    return sources.games.map((g) => path.resolve(HUB, g.source));
  }
  return targets.map((t) => {
    const known = sources.games.find((g) => g.id === t);
    if (known) return path.resolve(HUB, known.source);
    const dir = path.resolve(process.cwd(), t);
    if (!fs.existsSync(path.join(dir, 'cyd.game.json'))) {
      throw new Error(`"${t}" is neither a known game id nor a project with a cyd.game.json`);
    }
    return dir;
  });
}

// ---------- contract ------------------------------------------------------------

/** Validate a game project. Returns the resolved manifest; throws ContractError listing every problem. */
function checkContract(src) {
  const problems = [];
  const need = (ok, msg) => ok || problems.push(msg);
  const manifestFile = path.join(src, 'cyd.game.json');
  if (!fs.existsSync(manifestFile)) throw new ContractError(`${src}: missing cyd.game.json`);
  const m = readJson(manifestFile);
  const server = m.server ?? {};
  const contentDir = server.contentDir ?? 'content';

  need(/^[a-z][a-z0-9-]{1,30}$/.test(m.id ?? ''), 'id must be lowercase letters, digits or dashes (it becomes the URL /<id>/)');
  need(!RESERVED_IDS.has(m.id), `id "${m.id}" is reserved by the hub`);
  need(typeof m.name === 'string' && /^Can You /.test(m.name), 'name must start with "Can You "');
  need(typeof m.tagline === 'string' && m.tagline.length > 0 && m.tagline.length <= 90, 'tagline must be 1-90 characters');
  need(KINDS.includes(m.kind), `kind must be one of ${KINDS.join(', ')}`);
  need(/^#[0-9a-f]{6}$/i.test(m.accentColor ?? ''), 'accentColor must be a hex color like #c8461e (white text sits on it)');
  need(/^[A-Z][A-Z0-9]*$/.test(m.envPrefix ?? ''), 'envPrefix must be uppercase, e.g. CYS');
  need(typeof server.apiDir === 'string' && fs.existsSync(path.join(src, server.apiDir ?? '')), 'server.apiDir must point at the folder of API functions');
  need(Array.isArray(server.sources), 'server.sources must list the folders the API imports (e.g. ["lib"])');
  for (const s of server.sources ?? []) need(fs.existsSync(path.join(src, s)), `server.sources: ${s} does not exist`);
  need(Array.isArray(server.include) && server.include.length > 0, 'server.include must list the content files the API reads');

  // Daily system: one reset for every game, and puzzle #1 on the launch date.
  let launchDate = m.launchDate;
  let timezone = m.timezone;
  let resets = m.resets;
  if (m.config) {
    const cfgFile = path.join(src, m.config);
    if (fs.existsSync(cfgFile)) {
      const cfg = readJson(cfgFile);
      launchDate ??= cfg.launchDate;
      timezone ??= cfg.timezone;
      resets ??= cfg.resets;
    } else problems.push(`config: ${m.config} does not exist`);
  }
  need(/^\d{4}-\d{2}-\d{2}$/.test(launchDate ?? ''), 'launchDate (in cyd.game.json or its config file) must be YYYY-MM-DD');
  need(
    resets === undefined || Object.values(resets).every((t) => typeof t === 'string' && !Number.isNaN(Date.parse(t))),
    'resets must map YYYY-MM-DD days to ISO times',
  );
  need(timezone === HUB_TIMEZONE, `timezone must be ${HUB_TIMEZONE} so every game resets together (got ${timezone})`);

  // Hooks the hub relies on (see docs/GAME_CONTRACT.md).
  const serverDirs = [server.apiDir, ...(server.sources ?? [])].filter(Boolean).map((d) => path.join(src, d));
  const serverHas = (needle) => serverDirs.some((d) => grepDir(d, needle));
  if (m.envPrefix) {
    for (const suffix of ['CONTENT_DIR', 'DATA_DIR', 'KEY_PREFIX']) {
      need(serverHas(`${m.envPrefix}_${suffix}`), `server code never reads ${m.envPrefix}_${suffix}`);
    }
  }
  const webSrc = path.join(src, 'web/src');
  need(fs.existsSync(webSrc), 'web/src is missing (the client must be a Vite app rooted at web/)');
  need(grepDir(webSrc, 'VITE_API_BASE'), 'client never reads import.meta.env.VITE_API_BASE for its API path');
  need(grepDir(webSrc, 'cy:v1:'), 'client never writes the hub status key cy:v1:<id>:<date>');

  if (problems.length) {
    throw new ContractError(`${rel(src)} does not meet the game contract:\n${problems.map((p) => `    - ${p}`).join('\n')}`);
  }
  return { ...m, launchDate, timezone, resets, server: { ...server, contentDir } };
}

// ---------- import --------------------------------------------------------------

const ALLOWED_BARE = new Set(builtinModules);

/** Bare imports the copied server code needs. They must resolve from the hub's node_modules. */
function checkServerDeps(serverDir) {
  const hubPkg = readJson(path.join(HUB, 'package.json'));
  const hubDeps = new Set(Object.keys({ ...hubPkg.dependencies, ...hubPkg.devDependencies }));
  const missing = new Set();
  for (const f of walk(serverDir).filter((f) => /\.(ts|js|mjs)$/.test(f))) {
    const code = fs.readFileSync(f, 'utf8');
    for (const [, typeOnly, spec] of code.matchAll(/(?:^|\n)\s*(?:import|export)\s+(type\s+)?[^'"]*?from\s*['"]([^'"]+)['"]/g)) {
      // Type-only imports are erased at build time and need nothing at runtime.
      if (typeOnly || spec.startsWith('.') || spec.startsWith('node:') || ALLOWED_BARE.has(spec)) continue;
      const pkg = spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0];
      if (!hubDeps.has(pkg)) missing.add(pkg);
    }
  }
  if (missing.size) {
    throw new ContractError(`server code imports packages the hub does not have: ${[...missing].join(', ')}. Add them to the hub's package.json.`);
  }
}

/** Root-absolute URLs in the built page that escape /<id>/ will 404 or hit the hub. */
function checkBuiltUrls(webDir, id) {
  const bad = [];
  for (const f of walk(webDir).filter((f) => /\.(html|css)$/.test(f))) {
    const text = fs.readFileSync(f, 'utf8');
    for (const [, url] of text.matchAll(/(?:href|src)="(\/[^"]*)"|url\(\s*['"]?(\/[^'")]*)/g)) {
      if (url && !url.startsWith(`/${id}/`) && !url.startsWith('//')) bad.push(`${path.relative(webDir, f)}: ${url}`);
    }
  }
  if (bad.length) log(`  ! root-absolute URLs outside /${id}/ (they will not load):\n${bad.map((b) => `      ${b}`).join('\n')}`);
}

function importGame(src, { skipChecks }) {
  const m = checkContract(src);
  log(`\n▸ ${m.name} (${m.id}) from ${rel(src)}`);

  if (!skipChecks) {
    const scripts = readJson(path.join(src, 'package.json')).scripts ?? {};
    for (const s of ['typecheck', 'test']) {
      if (!scripts[s]) continue;
      step(`npm run ${s}`);
      run(src, 'npm', ['run', s, '--silent']);
    }
  }

  const staging = path.join(IMPORTED, `.staging-${m.id}`);
  fs.rmSync(staging, { recursive: true, force: true });

  step(`building client for /${m.id}/`);
  const webOut = path.join(staging, 'web');
  run(src, 'npx', ['vite', 'build', '--base', `/${m.id}/`, '--outDir', webOut, '--emptyOutDir', '--logLevel', 'warn'], {
    VITE_API_BASE: `/api/${m.id}`,
    VITE_CYD_HUB: '1',
  });
  checkBuiltUrls(webOut, m.id);

  step('copying server code and content');
  const serverOut = path.join(staging, 'server');
  for (const dir of [m.server.apiDir, ...m.server.sources]) {
    fs.cpSync(path.join(src, dir), path.join(serverOut, dir), {
      recursive: true,
      filter: (p) => !/\.(test|spec)\.[tj]sx?$/.test(p) && !p.includes(`${path.sep}__pycache__`),
    });
  }
  let contentFiles = 0;
  for (const pattern of m.server.include) {
    for (const f of fs.globSync(pattern, { cwd: src })) {
      const from = path.join(src, f);
      if (!fs.statSync(from).isFile()) continue;
      fs.cpSync(from, path.join(serverOut, f));
      contentFiles++;
    }
  }
  if (contentFiles === 0) throw new ContractError(`server.include matched no files in ${rel(src)}`);
  checkServerDeps(serverOut);

  const apiRoot = path.join(serverOut, m.server.apiDir);
  const routes = walk(apiRoot)
    .filter((f) => /\.ts$/.test(f) && !f.endsWith('.d.ts') && !path.basename(f).startsWith('_'))
    .map((f) => path.relative(apiRoot, f).replace(/\.ts$/, '').split(path.sep).join('/'))
    .sort();

  const commit = git(src, ['rev-parse', '--short', 'HEAD']);
  const dirty = commit ? (git(src, ['status', '--porcelain']) ?? '') !== '' : null;
  const resolved = {
    id: m.id,
    name: m.name,
    tagline: m.tagline,
    kind: m.kind,
    accentColor: m.accentColor,
    launchDate: m.launchDate,
    ...(m.resets ? { resets: m.resets } : {}),
    href: `/${m.id}/`,
    envPrefix: m.envPrefix,
    apiDir: m.server.apiDir,
    contentDir: m.server.contentDir,
    routes,
    source: { path: path.relative(HUB, src), commit, dirty },
    importedAt: new Date().toISOString(),
  };
  writeFile(path.join(staging, 'game.json'), JSON.stringify(resolved, null, 2) + '\n');

  // Swap in only once everything above succeeded, so a failed import leaves the last good one in place.
  const dest = path.join(IMPORTED, m.id);
  fs.rmSync(dest, { recursive: true, force: true });
  fs.renameSync(staging, dest);
  saveSource(m.id, src);

  step(`${routes.length} API routes, ${contentFiles} content files${commit ? `, commit ${commit}${dirty ? ' (with uncommitted changes)' : ''}` : ''}`);
}

// ---------- generated hub files ------------------------------------------------

function importedGames() {
  if (!fs.existsSync(IMPORTED)) return [];
  return fs
    .readdirSync(IMPORTED)
    .filter((d) => !d.startsWith('.') && fs.existsSync(path.join(IMPORTED, d, 'game.json')))
    .map((d) => readJson(path.join(IMPORTED, d, 'game.json')))
    .sort((a, b) => a.launchDate.localeCompare(b.launchDate) || a.id.localeCompare(b.id));
}

/** api/<id>/** entrypoints that set the game's env, then re-export its handler. */
function generateApi(games) {
  // Everything under api/_cyd and api/<imported id> is generated; anything else in api/ is the hub's own.
  fs.rmSync(path.join(API, '_cyd'), { recursive: true, force: true });
  for (const g of games) {
    fs.rmSync(path.join(API, g.id), { recursive: true, force: true });
    fs.rmSync(path.join(API, `${g.id}.ts`), { force: true });
  }

  for (const g of games) {
    const base = `imported/${g.id}/server`;
    writeFile(
      path.join(API, '_cyd', `${g.id}.ts`),
      `${GENERATED_HEADER}
// Runs before ${g.name}'s handlers load: points the game at its own content, local data and Redis keys.
import path from 'node:path';

// Vercel runs functions from the project root; the hub's dev server sets CYD_ROOT because it runs from apps/web.
const root = process.env.CYD_ROOT || process.cwd();
process.env.${g.envPrefix}_CONTENT_DIR ||= path.join(root, '${base}/${g.contentDir}');
process.env.${g.envPrefix}_DATA_DIR ||= path.join(root, '.data/${g.id}');
process.env.${g.envPrefix}_KEY_PREFIX ||= '${g.id}:';
`,
    );
    // One function per game (the Hobby plan caps a deployment at 12): api/<id>.ts dispatches to the game's
    // handlers. vercel.json rewrites /api/<id>/<route> to it with the route in ?__route.
    const imports = g.routes.map((route, i) => `import h${i} from '../${base}/${g.apiDir}/${route}.js';`);
    const table = g.routes.map((route, i) => `  '${route}': h${i},`);
    writeFile(
      path.join(API, `${g.id}.ts`),
      `${GENERATED_HEADER}
import './_cyd/${g.id}.js';
${imports.join('\n')}

type Req = { url?: string; query?: Record<string, unknown> };
type Handler = (req: any, res: any) => unknown;

const routes: Record<string, Handler> = {
${table.join('\n')}
};

export default function handler(req: Req, res: { statusCode: number; setHeader(k: string, v: string): void; end(body: string): void }) {
  // Vercel passes the route from the rewrite; the hub's dev server calls this with the original URL.
  const fromQuery = req.query?.__route;
  if (req.query) delete req.query.__route;
  const path = typeof fromQuery === 'string' ? fromQuery : new URL(req.url ?? '/', 'http://hub').pathname.slice('/api/${g.id}/'.length);
  const run = routes[path.split('/').filter(Boolean).join('/')];
  if (!run) {
    res.statusCode = 404;
    res.setHeader('Content-Type', 'application/json; charset=utf-8');
    res.end(JSON.stringify({ error: 'Not found' }));
    return;
  }
  return run(req, res);
}
`,
    );
  }
}

// vercel.json is generated too; Vercel rejects unknown keys, so it can't carry a "do not edit" note.
function generateVercel(games) {
  const config = {
    buildCommand: 'npm run build',
    outputDirectory: 'apps/web/dist',
    functions: Object.fromEntries(
      games.map((g) => [`api/${g.id}.ts`, { includeFiles: `imported/${g.id}/server/${g.contentDir}/**` }]),
    ),
    rewrites: [
      ...games.map((g) => ({ source: `/api/${g.id}/:route*`, destination: `/api/${g.id}?__route=:route*` })),
      // Static files win over rewrites on Vercel, so these only catch a game's client-side routes.
      ...games.flatMap((g) => [
        { source: `/${g.id}`, destination: `/${g.id}/index.html` },
        { source: `/${g.id}/:path*`, destination: `/${g.id}/index.html` },
      ]),
      { source: '/((?!api/).*)', destination: '/index.html' },
    ],
  };
  writeFile(path.join(HUB, 'vercel.json'), JSON.stringify(config, null, 2) + '\n');
}

function generateRegistry(games) {
  const entries = games.map(({ id, name, tagline, kind, accentColor, launchDate, resets, href }) => ({
    id,
    name,
    tagline,
    kind,
    accentColor,
    launchDate,
    ...(resets ? { resets } : {}),
    href,
  }));
  writeFile(
    GENERATED_REGISTRY,
    `${GENERATED_HEADER}
import type { ImportedGame } from '@cyd/shared';

export const importedGames: ImportedGame[] = ${JSON.stringify(entries, null, 2)};
`,
  );
}

function regenerate() {
  const games = importedGames();
  generateApi(games);
  generateVercel(games);
  generateRegistry(games);
  log(`\nHub updated: ${games.map((g) => g.id).join(', ') || 'no games'} (api/, vercel.json, ${rel(GENERATED_REGISTRY)})`);
}

// ---------- CLI ------------------------------------------------------------------

function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const flags = new Set(rest.filter((a) => a.startsWith('--')));
  const targets = rest.filter((a) => !a.startsWith('--'));

  if (cmd === 'import') {
    for (const src of resolveTargets(targets)) importGame(src, { skipChecks: flags.has('--skip-checks') });
    regenerate();
  } else if (cmd === 'check') {
    for (const src of resolveTargets(targets)) {
      const m = checkContract(src);
      log(`✓ ${m.name} (${m.id}) at ${rel(src)} meets the contract`);
    }
  } else if (cmd === 'regenerate') {
    regenerate();
  } else if (cmd === 'list') {
    const games = importedGames();
    if (!games.length) log('No games imported yet.');
    for (const g of games) {
      const commit = g.source.commit ? `${g.source.commit}${g.source.dirty ? '+dirty' : ''}` : 'no git';
      log(`${g.id.padEnd(10)} ${g.name.padEnd(20)} ${g.source.path} @ ${commit}, imported ${g.importedAt}`);
    }
  } else {
    log('Usage: node scripts/games.mjs <import|check|list|regenerate> [id|path ...] [--skip-checks]');
    process.exitCode = 1;
  }
}

try {
  main();
} catch (err) {
  console.error(`\n✗ ${err instanceof ContractError ? err.message : err.stack ?? err}`);
  process.exitCode = 1;
}
